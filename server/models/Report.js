const mongoose = require('mongoose');

const reportSchema = new mongoose.Schema({
  reportTitle: {
    type: String,
    required: [true, 'Report title is required'],
    trim: true
  },
  reportType: {
    type: String,
    enum: ['Comprehensive Executive Summary', 'Tree Census & Health', 'Green Coverage & AQI', 'Maintenance & Budgeting', 'Urban Forest Analytics'],
    default: 'Comprehensive Executive Summary'
  },
  generatedBy: {
    type: String,
    default: 'Chief Urban Horticulturist'
  },
  filterParams: {
    category: { type: String, default: 'All' },
    location: { type: String, default: 'All Zones' },
    status: { type: String, default: 'All' },
    startDate: { type: Date, default: null },
    endDate: { type: Date, default: null }
  },
  metrics: {
    totalParks: { type: Number, default: 0 },
    totalTrees: { type: Number, default: 0 },
    healthyTreesCount: { type: Number, default: 0 },
    totalForestHectares: { type: Number, default: 0 },
    totalGreenBeltKm: { type: Number, default: 0 },
    avgAqi: { type: Number, default: 0 },
    totalCarbonAbsorptionTonnes: { type: Number, default: 0 },
    pendingMaintenanceCount: { type: Number, default: 0 }
  },
  summaryNotes: {
    type: String,
    default: 'Automated executive summary generated by Digital Urban Greenery Management System.'
  }
}, {
  timestamps: true
});

module.exports = mongoose.model('Report', reportSchema);
